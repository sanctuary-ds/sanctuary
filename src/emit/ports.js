// Emits ready-to-use themes for terminals, bars and window managers, one per flavor.

import { resolveHex } from '../tokens.js';

const ANSI = ['black', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'white'];
const ANSI_16 = [...ANSI, ...ANSI.map((name) => `bright-${name}`)];

const header = (flavor, comment) =>
  `${comment} Sanctuary ${flavor.name} (${flavor.hour})\n${comment} Generated by scripts/build.js; do not edit by hand.\n`;

const kitty = (flavor, hex) => `${header(flavor, '#')}
foreground              ${hex('text')}
background              ${hex('surface')}
selection_foreground    ${hex('text')}
selection_background    ${hex('surface.raised-4')}
cursor                  ${hex('accent')}
cursor_text_color       ${hex('accent.on')}
url_color               ${hex('accent.lume')}
active_border_color     ${hex('accent')}
inactive_border_color   ${hex('lead')}
bell_border_color       ${hex('glass.amber')}
active_tab_foreground   ${hex('accent.on')}
active_tab_background   ${hex('accent')}
inactive_tab_foreground ${hex('text.muted')}
inactive_tab_background ${hex('surface.sunken')}
tab_bar_background      ${hex('surface.sunken')}

${ANSI_16.map((name, i) => `color${i} ${hex(`ansi.${name}`)}`).join('\n')}
`;

const ghostty = (flavor, hex) => `${header(flavor, '#')}
${ANSI_16.map((name, i) => `palette = ${i}=${hex(`ansi.${name}`)}`).join('\n')}
background = ${hex('surface')}
foreground = ${hex('text')}
cursor-color = ${hex('accent')}
cursor-text = ${hex('accent.on')}
selection-background = ${hex('surface.raised-4')}
selection-foreground = ${hex('text')}
`;

const tomlTable = (names, hex, prefix = '') =>
  names.map((name) => `${name.padEnd(7)} = "${hex(`ansi.${prefix}${name}`)}"`).join('\n');

const alacritty = (flavor, hex) => `${header(flavor, '#')}
[colors.primary]
background = "${hex('surface')}"
foreground = "${hex('text')}"
dim_foreground = "${hex('text.subtle')}"
bright_foreground = "${hex('text')}"

[colors.cursor]
text = "${hex('accent.on')}"
cursor = "${hex('accent')}"

[colors.selection]
text = "${hex('text')}"
background = "${hex('surface.raised-4')}"

[colors.normal]
${tomlTable(ANSI, hex)}

[colors.bright]
${tomlTable(ANSI, hex, 'bright-')}
`;

// base16 slots: 00-07 run from background to brightest foreground, 08-0F are the hues.
const BASE16 = [
  'surface', 'surface.raised-1', 'surface.raised-3', 'text.disabled', 'text.subtle', 'text', 'text', 'surface.inverse',
  'glass.ruby', 'glass.ember', 'glass.gilt', 'glass.verdure', 'glass.viridian', 'glass.cobalt', 'glass.amethyst', 'glass.murrey',
];

const base16 = (flavor, hex) => `${header(flavor, '#')}
system: "base16"
name: "Sanctuary ${flavor.name}"
author: "Sanctuary"
variant: "${flavor.scheme}"
palette:
${BASE16.map((path, i) => `  base0${i.toString(16).toUpperCase()}: "${hex(path)}"`).join('\n')}
`;

// Names shared by the GTK-CSS and Hyprland ports: enough to theme a bar and window borders.
const RICE = {
  surface: 'surface', 'surface-sunken': 'surface.sunken', 'surface-raised': 'surface.raised-2',
  text: 'text', 'text-muted': 'text.muted', 'text-subtle': 'text.subtle',
  lead: 'lead', 'lead-strong': 'lead.strong',
  accent: 'accent', 'accent-lume': 'accent.lume', 'accent-pane': 'accent.pane', 'accent-on': 'accent.on',
  danger: 'danger', warning: 'warning', success: 'success', info: 'info',
};

const riceEntries = (hex, pigments) => [
  ...Object.entries(RICE).map(([name, path]) => [name, hex(path)]),
  ...pigments.map((id) => [id, hex(`glass.${id}`)]),
];

const gtk = (flavor, hex, pigments) => `${header(flavor, '/*').replaceAll('\n', ' */\n')}
${riceEntries(hex, pigments).map(([name, value]) => `@define-color san-${name} ${value};`).join('\n')}
`;

const hyprland = (flavor, hex, pigments) => `${header(flavor, '#')}
${riceEntries(hex, pigments).map(([name, value]) => `$san-${name} = rgb(${value.slice(1)})`).join('\n')}
`;

const PORTS = {
  kitty: [kitty, '.conf'],
  ghostty: [ghostty, ''],
  alacritty: [alacritty, '.toml'],
  base16: [base16, '.yaml'],
  gtk: [gtk, '.css'],
  hyprland: [hyprland, '.conf'],
};

export function emitPorts(palette, tokens) {
  const files = {};
  const pigments = Object.keys(palette.pigments);
  for (const [id, flavor] of Object.entries(palette.flavors)) {
    const hex = (path) => resolveHex(tokens, id, path);
    for (const [app, [template, extension]] of Object.entries(PORTS)) {
      files[`${app}/sanctuary-${id}${extension}`] = template(flavor, hex, pigments);
    }
  }
  return files;
}
